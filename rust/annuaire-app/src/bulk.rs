/// What a series shows before it is written.
pub struct Proposal {
    pub title: String,
    pub summary: String,
    pub items: Vec<Item>,
    /// The rows of the table (one per item, or more: the lines refused by an import).
    pub rows: Vec<PreviewLine>,
    /// Titles of the columns « Attribute », « Before », « After », if others.
    pub columns: Option<[String; 3]>,
    /// The batches, if not those of the items (an undo).
    pub run: Option<Run>,
    pub undoes: Option<String>,
}

impl SeriesDialog {
    fn new(context: Arc<WriteContext>, proposal: Proposal) -> Self {
        let dialog: Self = glib::Object::new();
        let imp = dialog.imp();
        dialog.set_title(&proposal.title);
        imp.summary.set_label(&proposal.summary);
        if let Some([a, b, c]) = &proposal.columns {
            imp.attribute_column.set_title(Some(a));
            imp.before_column.set_title(Some(b));
            imp.after_column.set_title(Some(c));
        }
        imp.store.splice(0, 0, &objects(proposal.rows.clone()));
        if context.profile.read_only {
            imp.banner.set_title(&tr(
                "Read-only profile: no write possible. Edit the profile to write.",
            ));
            imp.banner.set_revealed(true);
        }
        let run = match proposal.run {
            Some(run) => run,
            None => {
                let chosen: Vec<usize> = (0..proposal.items.len()).collect();
                let batches = bulk::batches(&proposal.items, &chosen, bulk::BATCH_SIZE, &[])
                    .unwrap_or_default();
                Run::new(&proposal.title, batches)
            }
        };
        imp.batches_label
            .set_label(&bv::batches_summary(&run.batches));
        *imp.items.borrow_mut() = proposal.items;
        *imp.rows.borrow_mut() = proposal.rows;
        *imp.undoes.borrow_mut() = proposal.undoes;
        *imp.run.borrow_mut() = Some(run);
        let _ = imp.context.set(context);
        dialog.verify();
        dialog
    }

    fn context(&self) -> Arc<WriteContext> {
        self.imp()
            .context
            .get()
            .cloned()
            .expect("context set by new")
    }

    fn show(&self, parent: &impl IsA<gtk::Widget>) {
        let host = parent
            .root()
            .and_then(|r| r.dynamic_cast::<gtk::Widget>().ok())
            .unwrap_or_else(|| parent.as_ref().clone());
        *self.imp().host.borrow_mut() = Some(host);
        self.present(Some(parent.as_ref()));
    }

    fn host(&self) -> gtk::Widget {
        self.imp()
            .host
            .borrow()
            .clone()
            .unwrap_or_else(|| self.clone().upcast())
    }

    /// The label of an item, for the refusals.
    fn label(&self, item: usize) -> String {
        self.imp()
            .items
            .borrow()
            .get(item)
            .map(|i| i.label.clone())
            .unwrap_or_else(|| item.to_string())
    }

    /// The prior verification of every batch, on the write DC; the objects refused are left
    /// out of the batches and named.
    fn verify(&self) {
        let Some(run) = self.imp().run.borrow().clone() else {
            return;
        };
        let context = self.context();
        let weak = self.downgrade();
        glib::spawn_future_local(async move {
            let connection = context.connection.clone();
            let checked = gio::spawn_blocking(move || {
                let mut found = Vec::new();
                for (i, batch) in run.batches.iter().enumerate() {
                    let problems = writer::verify(&connection, &batch.changeset, catalog())?;
                    found.push((i, problems));
                }
                Ok::<_, annuaire_core::connection::Failure>((run, found))
            })
            .await;
            let Some(dialog) = weak.upgrade() else { return };
            let imp = dialog.imp();
            imp.check_spinner.set_spinning(false);
            imp.check_spinner.set_visible(false);
            let (run, found) = match checked {
                Ok(Ok(v)) => v,
                Ok(Err(failure)) => {
                    imp.check_state.set_label(&fill(
                        &tr("Check not possible: {message}"),
                        &[(
                            "message",
                            &errors::failure_problem(&failure, &dialog.context().profile.domain)
                                .message,
                        )],
                    ));
                    return;
                }
                Err(_) => return,
            };
            let mut refused = Vec::new();
            let mut texts = Vec::new();
            for (i, problems) in &found {
                let Some(batch) = run.batches.get(*i) else {
                    continue;
                };
                for item in bulk::refused_by_problems(batch, problems) {
                    if !refused.contains(&item) {
                        refused.push(item);
                    }
                }
                texts.extend(problems.iter().take(20).map(pv::problem_text));
            }
            dialog.verified(run, refused, &texts);
        });
    }

    fn verified(&self, mut run: Run, refused: Vec<usize>, texts: &[String]) {
        let imp = self.imp();
        let dc = self
            .context()
            .connection
            .state()
            .map_or_else(|| "?".to_owned(), |s| s.dc.clone());
        if refused.is_empty() {
            imp.check_state
                .set_label(&fill(&tr("Check passed. Writing on {dc}."), &[("dc", &dc)]));
        } else {
            let labels: Vec<String> = refused.iter().map(|&i| self.label(i)).collect();
            imp.check_state.set_label(&fill(
                &tr_n(
                    "The check on {dc} refused {n} object: it is left aside.",
                    "The check on {dc} refused {n} objects: they are left aside.",
                    refused.len() as u64,
                ),
                &[("dc", &dc), ("n", &refused.len().to_string())],
            ));
            imp.problems.set_label(&format!(
                "{}\n{}",
                bv::refused_text(&labels),
                texts.join("\n")
            ));
            imp.problems.set_visible(true);
            if trial() {
                eprintln!("essai masse refus : {}", labels.join(" | "));
            }
            let items = imp.items.borrow().clone();
            let _ = run.without(&items, &refused, bulk::BATCH_SIZE);
            imp.batches_label
                .set_label(&bv::batches_summary(&run.batches));
            imp.refused.borrow_mut().extend(refused);
        }
        let writable = !run.batches.is_empty() && !self.context().profile.read_only;
        *imp.run.borrow_mut() = Some(run);
        if trial() {
            eprintln!("essai masse vérifié : {}", imp.check_state.label());
        }
        if writable {
            imp.apply_button.set_sensitive(true);
            imp.apply_button.grab_focus();
        }
    }

    /// Writes the batches left, from a thread of its own.
    pub fn apply(&self) {
        let imp = self.imp();
        let Some(mut run) = imp.run.borrow_mut().take() else {
            return;
        };
        let context = self.context();
        let control = Control::new();
        if let Some(n) = std::env::var("ANNUAIRE_ESSAI_MASSE_ARRET")
            .ok()
            .and_then(|n| n.parse().ok())
            .filter(|_| run.next == 0)
        {
            control.stop_after(n);
        }
        *imp.control.borrow_mut() = Some(control.clone());
        imp.writing.set(true);
        imp.apply_button.set_sensitive(false);
        imp.close_button.set_sensitive(false);
        imp.button_stack.set_visible_child_name("attente");
        imp.follow_box.set_visible(false);
        imp.outcome.set_visible(false);
        imp.progress_box.set_visible(true);
        imp.stop_button.set_sensitive(true);
        self.set_can_close(false);
        let (start, total) = (run.rank, run.rank + run.left() - 1);
        let weak = self.downgrade();
        let watched = control.clone();
        glib::timeout_add_local(Duration::from_millis(200), move || {
            let Some(dialog) = weak.upgrade() else {
                return glib::ControlFlow::Break;
            };
            let imp = dialog.imp();
            if !imp.writing.get() {
                return glib::ControlFlow::Break;
            }
            let (ended, current, written) = watched.progress();
            let span = total.saturating_sub(start) + 1;
            imp.progress_bar
                .set_fraction((ended as f64 / span.max(1) as f64).min(1.0));
            imp.progress_bar
                .set_text(Some(&bv::progress_text(current.max(start), total, written)));
            glib::ControlFlow::Continue
        });
        let weak = self.downgrade();
        glib::spawn_future_local(async move {
            let (connection, profile, journal) = (
                context.connection.clone(),
                context.profile.clone(),
                context.journal.clone(),
            );
            let written = gio::spawn_blocking(move || {
                let end = run.write(&connection, &profile, &journal, &catalog(), &control);
                (run, end)
            })
            .await;
            let Some(dialog) = weak.upgrade() else { return };
            if let Ok((run, end)) = written {
                dialog.ended(run, end);
            }
        });
    }

    /// « Stop »: the series ends after the batch being written.
    pub fn stop(&self) {
        let imp = self.imp();
        if let Some(control) = imp.control.borrow().as_ref() {
            control.stop();
        }
        imp.stop_button.set_sensitive(false);
        imp.progress_bar
            .set_text(Some(&tr("Stopping after the batch being written…")));
    }

    #[allow(clippy::too_many_lines)]
    fn ended(&self, run: Run, end: End) {
        let imp = self.imp();
        imp.writing.set(false);
        imp.button_stack.set_visible_child_name("texte");
        imp.close_button.set_sensitive(true);
        imp.progress_box.set_visible(false);
        self.set_can_close(true);
        let host = self.host();
        if let Some(w) = host.downcast_ref::<crate::window::Window>() {
            for report in run.outcomes.iter().map(|o| &o.report) {
                if report.issue != Issue::Refused {
                    w.after_write(report);
                }
            }
        }
        let applied = run.applied().len();
        let written: usize = run
            .batches
            .iter()
            .take(run.next)
            .map(|b| b.all_items().len())
            .sum();
        let left: usize = run
            .batches
            .iter()
            .skip(run.next)
            .map(|b| b.all_items().len())
            .sum();
        let state = fill(
            &tr_n(
                "{lots} batch applied ({n} objects); {reste} objects left.",
                "{lots} batches applied ({n} objects); {reste} objects left.",
                applied as u64,
            ),
            &[
                ("lots", &applied.to_string()),
                ("n", &written.to_string()),
                ("reste", &left.to_string()),
            ],
        );
        let last = run.outcomes.last().cloned();
        let id = run.id.clone();
        let undoable = applied > 0 && imp.undoes.borrow().is_none();
        *imp.run.borrow_mut() = Some(run);
        let text = match &end {
            End::Finished => {
                if trial() {
                    eprintln!("essai masse fini : {state}");
                }
                self.close();
                let window = host.clone();
                let undo: Option<Box<dyn Fn()>> =
                    undoable.then(|| Box::new(move || propose_undo(&window, &id)) as Box<dyn Fn()>);
                writes::announce(
                    &host,
                    &fill(
                        &tr_n(
                            "{n} object written in {lots} batch.",
                            "{n} objects written in {lots} batches.",
                            written as u64,
                        ),
                        &[("n", &written.to_string()), ("lots", &applied.to_string())],
                    ),
                    undo,
                );
                return;
            }
            End::Stopped => format!(
                "{} {state} {}",
                tr("Stopped between two batches."),
                tr("What is written stays written: resume the series, or undo what it wrote.")
            ),
            End::Failed => {
                let report = last.as_ref().map(|o| &o.report);
                let detail = last
                    .as_ref()
                    .map(|o| pv::describe(&o.report, &o.problems))
                    .unwrap_or_default();
                let lead = match report.map(|r| r.issue) {
                    Some(Issue::Refused) => {
                        tr("A batch was refused by its check: nothing of it is written.")
                    }
                    Some(Issue::Cancelled) => tr("A batch failed and was rolled back entirely."),
                    _ => tr("A batch was left incomplete: see the history before going on."),
                };
                format!("{lead} {state}\n{detail}")
            }
            End::Error(e) => {
                let message = match e {
                    writer::ApplyError::Failure(f) => {
                        errors::failure_problem(f, &self.context().profile.domain).message
                    }
                    writer::ApplyError::Record(r) => r.message.clone(),
                };
                format!("{message} {state}")
            }
        };
        if trial() {
            eprintln!("essai masse arrêt : {}", text.replace('\n', " | "));
        }
        imp.outcome.set_label(&text);
        imp.outcome.set_visible(true);
        let incomplete = last
            .as_ref()
            .is_some_and(|o| o.report.issue == Issue::Incomplete);
        let resumable = !incomplete && imp.run.borrow().as_ref().is_some_and(|r| r.left() > 0);
        let version_only = last.as_ref().is_some_and(|o| {
            o.report.issue == Issue::Refused
                && !o.problems.is_empty()
                && o.problems
                    .iter()
                    .all(|p| p.kind == writer::ProblemKind::Version)
        });
        imp.resume_button.set_visible(resumable);
        imp.resume_button.set_label(&if matches!(end, End::Failed) {
            tr("Resume without the Refused")
        } else {
            tr("Resume")
        });
        imp.overwrite_button.set_visible(resumable && version_only);
        imp.undo_button.set_visible(undoable);
        imp.follow_box.set_visible(resumable || undoable);
    }

    /// The batches left, without the objects the last batch refused, if it did.
    pub fn resume(&self) {
        let imp = self.imp();
        {
            let mut guard = imp.run.borrow_mut();
            let Some(run) = guard.as_mut() else { return };
            let failed = run
                .outcomes
                .last()
                .filter(|o| o.report.issue != Issue::Applied)
                .cloned();
            if let (Some(outcome), Some(batch)) = (failed, run.batches.get(run.next).cloned()) {
                let mut refused = bulk::refused_by_problems(&batch, &outcome.problems);
                refused.extend(bulk::refused_by_report(&batch, &outcome.report));
                let items = imp.items.borrow().clone();
                if !refused.is_empty() && !items.is_empty() {
                    let _ = run.without(&items, &refused, bulk::BATCH_SIZE);
                    imp.refused.borrow_mut().extend(refused);
                }
            }
        }
        self.apply();
    }

    /// Writes the refused batch over the changes made since: its objects read again.
    pub fn overwrite(&self) {
        let Some(mut run) = self.imp().run.borrow_mut().take() else {
            return;
        };
        let changed = run.changed_since();
        let context = self.context();
        let weak = self.downgrade();
        glib::spawn_future_local(async move {
            let connection = context.connection.clone();
            let refreshed = gio::spawn_blocking(move || {
                let r = run.refresh(&connection, &changed);
                (run, r)
            })
            .await;
            let Some(dialog) = weak.upgrade() else { return };
            if let Ok((run, _)) = refreshed {
                *dialog.imp().run.borrow_mut() = Some(run);
                dialog.apply();
            }
        });
    }

    /// Undoes what the series wrote: the undo, previewed in a dialog of its own.
    pub fn undo(&self) {
        let Some(id) = self.imp().run.borrow().as_ref().map(|r| r.id.clone()) else {
            return;
        };
        let host = self.host();
        self.close();
        propose_undo(&host, &id);
    }

    // Trials.

    pub fn trial_verified(&self) -> bool {
        !self.imp().check_spinner.is_visible()
    }

    pub fn trial_apply(&self) -> bool {
        let ok = self.imp().apply_button.is_sensitive();
        if ok {
            self.apply();
        }
        ok
    }

    pub fn trial_writing(&self) -> bool {
        self.imp().writing.get()
    }

    pub fn trial_rows(&self) -> usize {
        self.imp().store.n_items() as usize
    }
}

/// Shows a change in bulk over `parent`.
pub fn propose(parent: &impl IsA<gtk::Widget>, proposal: Proposal) -> Option<SeriesDialog> {
    let Some(context) = writes::context(parent) else {
        writes::show_error(parent, &tr("Cannot write"), &tr("No domain is open."), "");
        return None;
    };
    if proposal.items.is_empty() && proposal.run.as_ref().is_none_or(|r| r.batches.is_empty()) {
        writes::announce(parent, &tr("No change."), None);
        return None;
    }
    let dialog = SeriesDialog::new(context, proposal);
    dialog.show(parent);
    if trial() {
        remember(&dialog);
    }
    Some(dialog)
}

/// The rows of the batches of an undo: the operations, as the common preview shows them.
fn undo_rows(batches: &[Batch]) -> Vec<PreviewLine> {
    batches
        .iter()
        .flat_map(|b| pv::lines(&b.changeset, None))
        .collect()
}

/// Proposes the undo of the series `id`: every batch of it that stays applied, the last first
/// (`bulk::undo`), in the dialog of the series.
pub fn propose_undo(widget: &impl IsA<gtk::Widget>, id: &str) {
    let Some(context) = writes::context(widget) else {
        return;
    };
    let reports = writer::read_journal(&context.journal);
    let title = reports
        .iter()
        .find_map(|r| r.series.as_ref().filter(|s| s.id == id))
        .map(|s| s.title.clone())
        .unwrap_or_default();
    let undo_title = fill(&tr("Undo of “{titre}”"), &[("titre", &title)]);
    match bulk::undo(
        &reports,
        &context.profile.domain,
        id,
        &undo_title,
        &AppCatalog,
    ) {
        Ok(run) if !run.batches.is_empty() => {
            let rows = undo_rows(&run.batches);
            let summary = fill(
                &tr_n(
                    "{n} batch of “{titre}” to undo, the last first.",
                    "{n} batches of “{titre}” to undo, the last first.",
                    run.batches.len() as u64,
                ),
                &[("n", &run.batches.len().to_string()), ("titre", &title)],
            );
            propose(
                widget,
                Proposal {
                    title: undo_title,
                    summary,
                    items: Vec::new(),
                    rows,
                    columns: None,
                    run: Some(run),
                    undoes: Some(id.to_owned()),
                },
            );
        }
        Ok(_) => writes::announce(widget, &tr("No change to undo."), None),
        Err(e) => writes::show_error(widget, &tr("Undo not possible"), &e.to_string(), ""),
    }
}

/// The series of `report`, if it belongs to one, undone whole (Ctrl+Z and the history).
pub fn undo_report(widget: &impl IsA<gtk::Widget>, report: &Report) -> bool {
    let Some(series) = &report.series else {
        return false;
    };
    propose_undo(widget, &series.id);
    true
}

