//! Export, import and changes in bulk (J9.8, J9.9, ADR 0026). Structures in
//! `dialogue-export.blp`, `dialogue-import.blp`, `dialogue-masse.blp` and `apercu-masse.blp`;
//! texts in `bulk_views`.
//!
//! The import and the changes of a selection end in the same dialog (`SeriesDialog`): the
//! preview, one object per row, the prior verification of every batch (the objects it refuses
//! are named and left aside), then the batches written one after the other with a bar of
//! progress and « Stop » between two batches. A series stopped or refused can be resumed, or
//! what it wrote undone; once written, the toast offers « Undo », and Ctrl+Z or the history
//! undo the whole series (`propose_undo`).
//!
//! The passwords generated by an import are written, before the first batch, in a file the
//! administrator chooses (mode 600); they are never shown nor journaled.

