fn objects(lines: Vec<PreviewLine>) -> Vec<glib::Object> {
    lines.into_iter().map(|l| Line::new(l).upcast()).collect()
}

/// The main window that holds `widget` (a dialog is presented inside it, or in a window
/// transient for it).
fn main_window(widget: &impl IsA<gtk::Widget>) -> Option<crate::window::Window> {
    let mut window = widget.root().and_downcast::<gtk::Window>();
    while let Some(w) = window {
        if let Ok(main) = w.clone().downcast::<crate::window::Window>() {
            return Some(main);
        }
        window = w.transient_for();
    }
    None
}

/// Where the dialogs and messages after a dialog go: its main window.
fn host_of(widget: &impl IsA<gtk::Widget>) -> gtk::Widget {
    main_window(widget).map_or_else(|| widget.as_ref().clone(), |w| w.upcast())
}

fn trial() -> bool {
    std::env::var_os("ANNUAIRE_ESSAI_MASSE").is_some()
}

