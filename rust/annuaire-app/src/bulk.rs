/// The file of the generated passwords, readable by its owner alone (ADR 0026 § 4).
pub fn write_passwords(
    path: &std::path::Path,
    generated: &[import::Generated],
) -> std::io::Result<()> {
    use std::io::Write as _;
    use std::os::unix::fs::OpenOptionsExt as _;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(path)?;
    file.write_all(import::passwords_file(generated, ';').as_bytes())?;
    file.sync_all()
}

